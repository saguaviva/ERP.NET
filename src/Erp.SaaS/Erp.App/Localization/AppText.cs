using System.Globalization;

namespace Erp.App.Localization;

public sealed class AppText
{
    private static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, string>> Dictionaries =
        new Dictionary<string, IReadOnlyDictionary<string, string>>(StringComparer.OrdinalIgnoreCase)
        {
            [AppLanguages.Spanish] = BuildSpanish(),
            [AppLanguages.Catalan] = BuildCatalan(),
            [AppLanguages.English] = BuildEnglish()
        };

    public string CurrentLanguage => AppLanguages.Normalize(CultureInfo.CurrentUICulture);

    public string this[string key] => Get(key);

    public string Get(string key)
    {
        var language = CurrentLanguage;
        if (Dictionaries.TryGetValue(language, out var selected) &&
            selected.TryGetValue(key, out var localized))
        {
            return localized;
        }

        if (Dictionaries[AppLanguages.Spanish].TryGetValue(key, out var fallback))
        {
            return fallback;
        }

        return key;
    }

    public string Format(string key, params object[] args) =>
        string.Format(CultureInfo.CurrentCulture, Get(key), args);

